const realFetch = globalThis.fetch;
function pageFor(work) {
  const text = (value, type = "rich_text") => ({ type, [type]: [{ type: "text", plain_text: value, text: { content: value } }] });
  return {
    object: "page", id: work.id, url: "https://www.notion.so/" + work.id, cover: null, icon: null,
    properties: {
      Title: text(work.title, "title"), Slug: text(work.slug), Description: text(work.description),
      Status: { type: "select", select: { name: work.status } },
      Category: { type: "select", select: work.category ? { name: work.category } : null },
      Tags: { type: "multi_select", multi_select: work.tags.map((name) => ({ name })) },
      Platforms: { type: "multi_select", multi_select: work.platforms.map((name) => ({ name })) },
      Featured: { type: "checkbox", checkbox: work.featured },
      Thumbnail: { type: "files", files: work.hasThumbnail ? [{ name: "fixture.svg", type: "external", external: { url: "https://secure.notion-static.com/fixtures/" + work.slug + ".svg" } }] : [] },
    },
  };
}
globalThis.fetch = async function(input, options) {
  const url = new URL(typeof input === "string" || input instanceof URL ? input : input.url);
  if (url.hostname !== "api.notion.com") return realFetch(input, options);
  const path = url.pathname;
  let response;
  if (path.startsWith("/v1/databases/")) {
    response = { object: "database", data_sources: [{ id: path.includes("news") ? "fixture-news-source" : "fixture-games-source" }] };
  } else if (path.startsWith("/v1/data_sources/")) {
    const args = JSON.parse(options?.body || "{}");
    let works = path.includes("news") ? [] : fixtures;
    if (args.filter?.property === "Slug") works = works.filter((work) => work.slug === args.filter.rich_text.equals);
    if (args.filter?.property === "Status" && args.filter.select.equals) works = works.filter((work) => work.status === args.filter.select.equals);
    const offset = Number(args.start_cursor || 0), size = args.page_size || 8;
    response = { object: "list", results: works.slice(offset, offset + size).map(pageFor), has_more: offset + size < works.length, next_cursor: offset + size < works.length ? String(offset + size) : null };
  } else if (path.startsWith("/v1/pages/")) {
    const work = fixtures.find((work) => work.id === path.split("/").pop().replaceAll("-", ""));
    response = work ? pageFor(work) : { object: "error", message: "Unknown fixture" };
  } else if (path.startsWith("/v1/blocks/")) {
    response = { object: "list", results: [], has_more: false, next_cursor: null };
  } else {
    throw new Error("Unexpected Notion fixture request: " + path);
  }
  return new Response(JSON.stringify(response), { status: 200, headers: { "content-type": "application/json" } });
};
